#!/usr/bin/env python3
"""The authority manifest of each [[bin]] that is a tool (here: stats): derived by the compiler, embedded by the build, gated against a ceiling (cancho docs/agent-toolbox.md D12).

    python3 scripts/manifest.py            # derive, write manifests/<tool>.authority.json and generated/<tool>/built.cho, check the fixed point and the ceiling
    python3 scripts/manifest.py --check    # change nothing; exit 1 on drift, on a label outside tools.toml, on an unbounded authority, or on a foreign symbol

For the tool, pass 1 runs `cancho authority <sources and installed dependencies> --std --output json`, writes the committed record and the generated module (the authority, schemas/<tool>.v1.json and the
compiler pin as string literals); pass 2 derives again with the generated file in place and requires the same report (the fixed point). The compiler is $CANCHO. Run `cancho install` first (build/deps).
"""
import json
import os
import pathlib
import subprocess
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[1]
CANCHO = os.environ.get("CANCHO", str(ROOT.parent / "cancho-compiler-a4572ea" / "target" / "release" / "cancho"))
FORBIDDEN = {"ffi", "net_out", "net_in", "clock", "conc"}
TOOLS = ["stats"]


def sources(tool):
    cfg = tomllib.loads((ROOT / "cancho.toml").read_text())
    for b in cfg["bin"]:
        if b["name"] == tool:
            out = []
            for s in b["sources"]:
                p = ROOT / s
                out += sorted(str(f) for f in (p.glob("*.cho") if p.is_dir() else [p]))
            return out
    raise SystemExit("no [[bin]] named %s" % tool)


def derive(tool):
    deps = sorted(str(f) for f in (ROOT / "build" / "deps").glob("*.cho"))
    if not deps:
        raise SystemExit("no build/deps: run `cancho install` first")
    r = subprocess.run([CANCHO, "authority"] + sources(tool) + deps + ["--std", "--output", "json"], capture_output=True, text=True, cwd=ROOT)
    if r.returncode != 0:
        raise SystemExit("cancho authority failed:\n" + r.stderr[-800:])
    doc = json.loads(r.stdout)
    return {"bounded": doc["bounded"], "unbounded_by": doc["unbounded_by"], "effects": doc["effects"], "labels": doc["labels"], "foreign_symbols": doc["foreign_symbols"]}


def literal(text):
    # a cancho string literal: six escapes and nothing else
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t") + '"'


def built_text(tool, authority):
    schema = json.dumps(json.loads((ROOT / "schemas" / (tool + ".v1.json")).read_text()), separators=(",", ":"))
    rev = tomllib.loads((ROOT / "cancho.toml").read_text())["package"]["cancho"]
    a = json.dumps(authority, separators=(",", ":"))
    return ("edition 5;\n\nmodule toolbox.built;\n\n// Generated by scripts/manifest.py -- do not edit. The compiler's authority report for this tool, the tool's JSON Schema, and the compiler it was written for,\n"
            "// as `introspect` prints them (cancho docs/agent-toolbox.md D12). This module is not in cancho-tools' contract package: each tool has its own.\n\n"
            "pub fn authority() -> [] &static [byte] {\n    return %s;\n}\n\npub fn schema() -> [] &static [byte] {\n    return %s;\n}\n\npub fn compiler() -> [] &static [byte] {\n    return %s;\n}\n" % (literal(a), literal(schema), literal(rev)))


def ceiling(tool, authority):
    allow = set(tomllib.loads((ROOT / "tools.toml").read_text())[tool]["allow"])
    bad = []
    for lab in authority["labels"]:
        shown = lab["name"] + ('("%s")' % lab["argument"] if lab["argument"] is not None else "")
        if lab["name"] in FORBIDDEN:
            bad.append("%s holds %s, which no tool may" % (tool, shown))
        elif shown not in allow:
            bad.append("%s derives %s, which tools.toml does not allow" % (tool, shown))
    if not authority["bounded"]:
        bad.append("%s is not bounded" % tool)
    if authority["foreign_symbols"]:
        bad.append("%s reaches a foreign symbol" % tool)
    return bad


def main():
    check = "--check" in sys.argv
    problems = []
    for tool in TOOLS:
        gen = ROOT / "generated" / tool / "built.cho"
        man = ROOT / "manifests" / (tool + ".authority.json")
        a1 = derive(tool)
        text = built_text(tool, a1)
        mtext = json.dumps(a1, indent=2) + "\n"
        if check:
            if not gen.exists() or gen.read_text() != text:
                problems.append("%s: generated/%s/built.cho differs from a fresh derivation" % (tool, tool))
            if not man.exists() or man.read_text() != mtext:
                problems.append("manifests/%s.authority.json differs from a fresh derivation" % tool)
        else:
            gen.parent.mkdir(parents=True, exist_ok=True)
            man.parent.mkdir(parents=True, exist_ok=True)
            gen.write_text(text)
            man.write_text(mtext)
            a2 = derive(tool)
            if a2 != a1:
                problems.append("%s: the authority is not a fixed point (it changed when the generated module was written)" % tool)
        problems += ceiling(tool, a1)
    for p in problems:
        print("manifest: " + p)
    if problems:
        return 1
    print("manifest: ok (%s)" % ", ".join(TOOLS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
